#!/usr/bin/env python3
"""Builds tools/clean-catalog.tsv, the list the phone installer offers to disable, from cleanyourtv's per-TV lists.

cleanyourtv (github.com/Gathin23/cleanyourtv, MIT) keeps one examples/<tv>/debloat.txt per TV model, written and
tested by the people who own them. This folds them into one row per package: how many TVs disable it, the kind of
thing it is (from the section it sits under), and a note. The installer reads the result from this repo's main
branch, so a refresh here reaches every installer without updating it.

    git clone --depth 1 https://github.com/Gathin23/cleanyourtv /tmp/cleanyourtv
    python3 tools/gen-clean-catalog.py /tmp/cleanyourtv > tools/clean-catalog.tsv

Kinds, in the order they are checked: demo, tracking, ads, launcher, apps, background. "kept" counts the TVs whose
notes say to keep a package (the installer never ticks those for you); a few packages are never offered (NEVER).
"""
import collections
import glob
import os
import re
import subprocess
import sys

PACKAGE = re.compile(r"^([a-zA-Z][\w]*(?:\.[\w-]+)+)\s*(?:#\s*(.*))?$")
ANY_PACKAGE = re.compile(r"\b([a-z][\w]*(?:\.[a-z0-9_]+){2,})\b")

KINDS = [
    ("demo", r"demo|retail|shop mode|hotel|store mode"),
    ("tracking", r"telemetry|track|analytic|metric|\blog|acr\b|attribution|diagnos|feedback|usage report|crash report"),
    ("ads", r"\bads?\b|advert|sponsor|promo|content row|recommend|feed|patchwall|shopping|auto-?install|push"),
    ("apps", r"preload|streaming|choice|not used|unused|optional|extras|personal|games?\b|owner"),
    ("background", r"background|service|sync|cloud|google extras|not needed|nobody"),
]
# Never offered, whatever a list says: Afnon itself, and what keeps a TV usable or reachable over ADB.
NEVER = re.compile(
    r"^tv\.afnon\.|^android$|^com\.android\.(systemui|settings|tv\.settings|shell|packageinstaller|permissioncontroller|"
    r"providers\.|inputmethod|externalstorage|webview)|^com\.google\.android\.(gms|gsf|webview|tv\.remote\.service|"
    r"packageinstaller|permissioncontroller|inputmethod)|inputmethod|tvinput|\.tv\.settings$|bluetooth|wifi|networkstack")


def kind_of(section, package):
    if "launcher" in package or "setupwraith" in package:
        return "launcher"
    text = (section or "").lower()
    for name, pattern in KINDS:
        if re.search(pattern, text):
            return name
    return "background"


def main(root):
    tvs = collections.Counter()
    kinds = collections.defaultdict(collections.Counter)
    notes = collections.defaultdict(collections.Counter)
    kept = collections.Counter()
    files = sorted(glob.glob(os.path.join(root, "examples", "*", "debloat.txt")))
    for path in files:
        lines = open(path, encoding="utf-8").read().split("\n")
        i = 0
        while i < len(lines) and lines[i].lstrip().startswith("#"):
            if re.search(r"\bkeep\b", lines[i], re.I):
                kept.update(set(ANY_PACKAGE.findall(lines[i])))
            i += 1
        section = None
        seen = set()
        for raw in lines[i:]:
            line = raw.strip()
            if not line:
                continue
            if line.startswith("#"):
                body = line.lstrip("#").strip()
                if body and not PACKAGE.match(body):
                    section = body.strip("- ")
                continue
            m = PACKAGE.match(line)
            if not m or m.group(1) in seen:
                continue
            package = m.group(1)
            seen.add(package)
            tvs[package] += 1
            kinds[package][kind_of(section, package)] += 1
            note = (m.group(2) or "").strip()
            if note:
                notes[package][note] += 1

    try:
        commit = subprocess.run(["git", "-C", root, "rev-parse", "--short", "HEAD"], capture_output=True,
                                text=True).stdout.strip()
    except OSError:
        commit = ""
    out = sys.stdout
    out.write("# Generated by tools/gen-clean-catalog.py from cleanyourtv (github.com/Gathin23/cleanyourtv, MIT)"
              f"{' @ ' + commit if commit else ''}: {len(files)} TV lists. Do not edit by hand.\n")
    out.write("# package\ttvs\tkept\tkind\tnote\n")
    rows = []
    for package, count in tvs.items():
        if NEVER.search(package):
            continue
        kind = kinds[package].most_common(1)[0][0]
        # The shortest of the commonest notes reads best on a phone.
        note = ""
        if notes[package]:
            top = notes[package].most_common(3)
            note = min((n for n, _ in top), key=len).replace("\t", " ")[:120]
        rows.append((package, count, kept[package], kind, note))
    for package, count, keep, kind, note in sorted(rows, key=lambda r: (-r[1], r[0])):
        out.write(f"{package}\t{count}\t{keep}\t{kind}\t{note}\n")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else ".")
